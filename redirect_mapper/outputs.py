"""Writers for server and plugin redirect formats."""
from __future__ import annotations

import csv
import io
import json
import re
from typing import Dict, Iterable, List, Optional, Tuple
from urllib.parse import quote, unquote

from .matching import MapResult, Match
from .urls import UrlRecord

FORMATS = ("nginx-map", "nginx-return", "apache", "cloudflare", "wordpress", "json")
FILENAMES = {
    "nginx-map": "nginx-redirect-map.conf",
    "nginx-return": "nginx-redirects.conf",
    "apache": "redirects.htaccess",
    "cloudflare": "cloudflare-bulk-redirects.csv",
    "wordpress": "wordpress-redirection.csv",
    "json": "report.json",
}
HEADER = "Generated by redirect-mapper - review before deploying."


def _target_ok(match: Match) -> bool:
    return bool(match.target) and not match.target.startswith("#")


def _dedupe(matches: Iterable[Match]) -> List[Match]:
    """Keep the first redirect per source request URI."""
    seen = set()
    out = []
    for m in matches:
        key = (m.old.host or "", m.old.request_uri)
        if key in seen or not _target_ok(m):
            continue
        seen.add(key)
        out.append(m)
    return out


def _variants(rec: UrlRecord) -> List[str]:
    """Request URIs to match: with and without trailing slash for plain paths."""
    uri = rec.request_uri
    if rec.query or rec.path == "/":
        return [uri]
    if rec.path.endswith("/"):
        return [uri, rec.path.rstrip("/")]
    return [uri, rec.path + "/"]


def _nginx_quote(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _safe_target(target: str) -> str:
    """Make a target safe for Nginx/Apache config (no variables, quotes, spaces)."""
    return quote(target, safe="/:?&=%#@!*()',+;~-._")


def to_nginx_map(matches: List[Match], map_name: str = "redirect_target") -> str:
    lines = [
        "# %s" % HEADER,
        "# Place the map block in the http {} context, e.g. conf.d/redirects.conf.",
        "# Then add to each server {}:",
        "#   if ($%s) { return 301 $%s; }" % (map_name, map_name),
        "map $request_uri $%s {" % map_name,
        '    default "";',
    ]
    seen = set()
    for m in _dedupe(matches):
        for uri in _variants(m.old):
            if uri in seen:
                continue
            seen.add(uri)
            lines.append("    %s %s;" % (_nginx_quote(uri), _nginx_quote(_safe_target(m.target))))
    lines.append("}")
    return "\n".join(lines) + "\n"


def to_nginx_return(matches: List[Match]) -> str:
    lines = ["# %s" % HEADER,
             "# Include inside a server {} block. Query-string sources use `if ($args)`."]
    seen = set()
    for m in _dedupe(matches):
        target = _nginx_quote(_safe_target(m.target))
        if m.old.query:
            key = ("q", m.old.request_uri)
            if key in seen:
                continue
            seen.add(key)
            lines.append("if ($request_uri = %s) { return 301 %s; }"
                         % (_nginx_quote(m.old.request_uri), target))
            continue
        for uri in _variants(m.old):
            if uri in seen:
                continue
            seen.add(uri)
            lines.append("location = %s { return 301 %s; }" % (_nginx_quote(uri), target))
    return "\n".join(lines) + "\n"


def _apache_regex(text: str) -> str:
    """Escape text for an Apache regex; keeps ``/``, ``-`` and ``%`` readable."""
    return re.escape(text).replace("\\/", "/").replace("\\-", "-").replace("\\%", "%")


def _apache_path(path: str) -> str:
    """Apache matches Redirect/RedirectMatch against the percent-DECODED path."""
    return unquote(path).replace('"', "%22")


def to_apache(matches: List[Match], style: str = "match") -> str:
    """Apache .htaccess rules. ``style`` is ``match`` (RedirectMatch) or ``redirect``."""
    lines = ["# %s" % HEADER]
    if style == "redirect":
        lines.append("# NOTE: Redirect matches by PREFIX: /a also redirects /a-long-slug.")
    plain, queries = [], []
    seen = set()
    for m in _dedupe(matches):
        key = m.old.request_uri
        if key in seen:
            continue
        seen.add(key)
        (queries if m.old.query else plain).append(m)
    for m in plain:
        target = _safe_target(m.target)
        if style == "redirect":
            src = _apache_path(m.old.path.rstrip("/") or "/")
            lines.append('Redirect 301 %s "%s"' % (src, target))
        else:
            base = _apache_path(m.old.path.rstrip("/"))
            pattern = "^%s/?$" % _apache_regex(base) if base else "^/$"
            lines.append('RedirectMatch 301 "%s" "%s"' % (pattern, target))
    if queries:
        lines += ["", "# Query-string sources need mod_rewrite.", "<IfModule mod_rewrite.c>",
                  "RewriteEngine On"]
        for m in queries:
            lines.append("RewriteCond %%{QUERY_STRING} ^%s$" % _apache_regex(m.old.query))
            rule_path = _apache_regex(_apache_path(m.old.path.lstrip("/")))
            lines.append("RewriteRule ^%s$ %s? [R=301,L]" % (rule_path, _safe_target(m.target)))
        lines.append("</IfModule>")
    return "\n".join(lines) + "\n"


def to_cloudflare(matches: List[Match]) -> Tuple[str, int]:
    """Cloudflare Bulk Redirects CSV. Returns ``(csv_text, skipped_count)``.

    Rows without a known source host or with query strings are skipped.
    """
    buf = io.StringIO()
    writer = csv.writer(buf, lineterminator="\n")
    writer.writerow(["source_url", "target_url", "status_code", "preserve_query_string",
                     "include_subdomains", "subpath_matching", "preserve_path_suffix"])
    skipped = 0
    seen = set()
    for m in _dedupe(matches):
        if not m.old.host or m.old.query:
            skipped += 1
            continue
        source = m.old.host + (m.old.path if m.old.path != "/" else "/")
        if source in seen:
            continue
        seen.add(source)
        writer.writerow([source, m.target, 301, "false", "false", "false", "false"])
    return buf.getvalue(), skipped


def to_wordpress_redirection(matches: List[Match]) -> str:
    """CSV for the Redirection plugin's importer: source,target,regex,code."""
    buf = io.StringIO()
    writer = csv.writer(buf, lineterminator="\n")
    writer.writerow(["source", "target", "regex", "code"])
    seen = set()
    for m in _dedupe(matches):
        src = m.old.request_uri
        if src in seen:
            continue
        seen.add(src)
        writer.writerow([src, m.target, 0, 301])
    return buf.getvalue()


def build_report(result: MapResult, issues: Optional[List[Dict[str, object]]] = None,
                 meta: Optional[Dict[str, object]] = None) -> Dict[str, object]:
    total = len(result.matches) + len(result.unmatched) + len(result.unchanged)
    return {
        "summary": {
            "old_urls": total,
            "matched": len(result.matches),
            "unmatched": len(result.unmatched),
            "unchanged": len(result.unchanged),
            "by_method": result.by_method(),
            "average_confidence": round(
                sum(m.confidence for m in result.matches) / len(result.matches), 3
            ) if result.matches else 0.0,
        },
        "meta": meta or {},
        "matches": [m.to_dict() for m in result.matches],
        "unmatched": [u.to_dict() for u in result.unmatched],
        "unchanged": [r.url for r in result.unchanged],
        "issues": issues or [],
    }


def to_json(report: Dict[str, object]) -> str:
    return json.dumps(report, indent=2, ensure_ascii=False) + "\n"


def unmatched_csv(result: MapResult) -> str:
    buf = io.StringIO()
    writer = csv.writer(buf, lineterminator="\n")
    writer.writerow(["old_url", "suggestion_1", "score_1", "suggestion_2", "score_2",
                     "suggestion_3", "score_3"])
    for u in result.unmatched:
        row: List[object] = [u.old.url]
        for url, score in u.suggestions:
            row += [url, score]
        writer.writerow(row)
    return buf.getvalue()
